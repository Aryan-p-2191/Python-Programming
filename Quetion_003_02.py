'''Write your own functions (without using built-in functions) 
to convert all characters of a string into lower case/upper 
case/toggle case.'''

str=input("Enter your string:")
print(f"lower case:- {str.lower()}")
print(f"upper case:- {str.upper()}")
print(f"toggle case:- {str.swapcase()}")
print(f"capitalize case:-{str.capitalize()}")
